-- ── 7. release_expired_holds RPC (called by pg_cron every minute) ─────────────

CREATE OR REPLACE FUNCTION public.release_expired_holds()
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_released INTEGER := 0;
    v_rec      RECORD;
BEGIN
    FOR v_rec IN
        SELECT id, flight_block_id, guest_count
        FROM public.package_reservations
        WHERE status = 'ACTIVE_HOLD'
          AND hold_expires_at < now()
        FOR UPDATE SKIP LOCKED
    LOOP
        -- Return seats to the flight block
        UPDATE public.flight_blocks
        SET allocated_seats = GREATEST(0, allocated_seats - v_rec.guest_count),
            updated_at = now()
        WHERE id = v_rec.flight_block_id;

        -- Mark reservation as released
        UPDATE public.package_reservations
        SET status = 'RELEASED', updated_at = now()
        WHERE id = v_rec.id;

        v_released := v_released + 1;
    END LOOP;

    RETURN v_released;
END;
$$;

