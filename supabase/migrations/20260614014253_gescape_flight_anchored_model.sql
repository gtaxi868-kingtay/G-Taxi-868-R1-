GRANT EXECUTE ON FUNCTION public.release_expired_holds() TO service_role;

-- ── 8. check_flight_tipping_points RPC (called daily at T-3 days) ─────────────
--
-- For each POOLING block past its cancel_deadline:
--   - If allocated_seats >= tipping_point_seats → CONFIRMED (flight goes)
--   - Otherwise → CANCELLED (seats released, pre-auths voided)

CREATE OR REPLACE FUNCTION public.check_flight_tipping_points()
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_block RECORD;
BEGIN
    FOR v_block IN
        SELECT id, tipping_point_seats, allocated_seats, departure_time
        FROM public.flight_blocks
        WHERE status = 'POOLING'
          AND cancel_deadline <= now()
        FOR UPDATE
    LOOP
        IF v_block.allocated_seats >= v_block.tipping_point_seats THEN
            UPDATE public.flight_blocks
            SET status = 'CONFIRMED', confirmed_at = now(), updated_at = now()
            WHERE id = v_block.id;

            UPDATE public.package_reservations
            SET status = 'CONFIRMED', confirmed_at = now(), updated_at = now()
            WHERE flight_block_id = v_block.id AND status = 'CAPTURED';
        ELSE
            UPDATE public.flight_blocks
            SET status = 'CANCELLED', updated_at = now()
            WHERE id = v_block.id;

            -- Return seats and cancel reservations
            UPDATE public.package_reservations
            SET status = 'CANCELLED', updated_at = now()
            WHERE flight_block_id = v_block.id AND status IN ('ACTIVE_HOLD', 'CAPTURED');

            UPDATE public.flight_blocks
            SET allocated_seats = 0, updated_at = now()
            WHERE id = v_block.id;
        END IF;
    END LOOP;
END;
$$;

