-- ── 6. secure_escape_booking RPC ─────────────────────────────────────────────
--
-- Atomic pessimistic lock: locks flight_blocks row FOR UPDATE, validates both
-- lodging occupancy rules and seat availability, then creates a 10-minute hold.
-- Returns success, message, reservation_id, total_price_cents, hold_expires_at.

CREATE OR REPLACE FUNCTION public.secure_escape_booking(
    p_escape_package_id  UUID,
    p_rider_id           UUID,
    p_guest_count        INTEGER,
    p_payment_method     TEXT DEFAULT 'stripe',
    p_pickup_address     TEXT DEFAULT NULL,
    p_pickup_lat         DOUBLE PRECISION DEFAULT NULL,
    p_pickup_lng         DOUBLE PRECISION DEFAULT NULL,
    p_passenger_names    JSONB DEFAULT '[]',
    p_special_requests   TEXT DEFAULT NULL
)
RETURNS TABLE (
    success          BOOLEAN,
    message          TEXT,
    reservation_id   UUID,
    total_price_cents INTEGER,
    hold_expires_at  TIMESTAMPTZ,
    seats_remaining  INTEGER,
    requires_verification BOOLEAN
)
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_flight_id          UUID;
    v_lodging_id         UUID;
    v_min_guests         INTEGER;
    v_max_guests         INTEGER;
    v_seats_avail        INTEGER;
    v_flight_status      TEXT;
    v_price_per_person   INTEGER;
    v_requires_verif     BOOLEAN;
    v_total_price        INTEGER;
    v_reservation_id     UUID;
    v_hold_expires       TIMESTAMPTZ;
    v_reserve_cents      INTEGER;
BEGIN
    -- 1. Fetch package (fail fast if inactive)
    SELECT ep.flight_block_id, ep.lodging_node_id, ep.price_per_person_cents
    INTO v_flight_id, v_lodging_id, v_price_per_person
    FROM public.escape_packages ep
    WHERE ep.id = p_escape_package_id AND ep.is_active = TRUE;

    IF NOT FOUND THEN
        RETURN NEXT(FALSE, 'Package not found or no longer available.',
                    NULL, NULL, NULL, NULL, NULL);
        RETURN;
    END IF;

    -- 2. Validate lodging occupancy rules
    SELECT ln.min_guests, ln.max_guests, ln.requires_verification
    INTO v_min_guests, v_max_guests, v_requires_verif
    FROM public.lodging_nodes ln
    WHERE ln.id = v_lodging_id;

    IF p_guest_count < v_min_guests OR p_guest_count > v_max_guests THEN
        RETURN NEXT(
            FALSE,
            'Guest count must be between ' || v_min_guests || ' and ' || v_max_guests || ' for this property.',
            NULL, NULL, NULL, NULL, v_requires_verif
        );
        RETURN;
    END IF;

    -- 3. Lock flight block row — prevents race conditions during concurrent buys
    SELECT (fb.total_capacity_seats - fb.allocated_seats), fb.status
    INTO v_seats_avail, v_flight_status
    FROM public.flight_blocks fb
    WHERE fb.id = v_flight_id
    FOR UPDATE;

    IF v_flight_status = 'CANCELLED' THEN
        RETURN NEXT(FALSE, 'This flight has been cancelled.', NULL, NULL, NULL, 0, NULL);
        RETURN;
    END IF;

    IF v_seats_avail < p_guest_count THEN
        RETURN NEXT(
            FALSE,
            'Only ' || v_seats_avail || ' seat(s) remaining on this flight.',
            NULL, NULL, NULL, v_seats_avail, NULL
        );
        RETURN;
    END IF;

    -- 4. Atomically allocate seats
    UPDATE public.flight_blocks
    SET allocated_seats = allocated_seats + p_guest_count,
        updated_at = now()
    WHERE id = v_flight_id;

    -- 5. Compute pricing
    v_total_price  := v_price_per_person * p_guest_count;
    v_reserve_cents := ROUND(v_total_price * 0.015);
    v_hold_expires := now() + INTERVAL '10 minutes';

    -- 6. Create the hold record
    INSERT INTO public.package_reservations (
        escape_package_id, flight_block_id, rider_id, guest_count,
        total_price_cents, status, payment_method, hold_expires_at,
        pickup_address, pickup_lat, pickup_lng,
        passenger_names, special_requests, reserve_amount_cents
    ) VALUES (
        p_escape_package_id, v_flight_id, p_rider_id, p_guest_count,
        v_total_price, 'ACTIVE_HOLD', p_payment_method, v_hold_expires,
        p_pickup_address, p_pickup_lat, p_pickup_lng,
        p_passenger_names, p_special_requests, v_reserve_cents
    ) RETURNING id INTO v_reservation_id;

    RETURN NEXT(
        TRUE,
        'Seats held. Complete payment within 10 minutes to secure your escape.',
        v_reservation_id,
        v_total_price,
        v_hold_expires,
        v_seats_avail - p_guest_count,
        v_requires_verif
    );
    RETURN;
END;
$$;

